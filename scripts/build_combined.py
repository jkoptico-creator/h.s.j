"""Build the shareable single HTML edition from the six canonical pages.

Python standard library only. Run from any directory; do not edit the generated file.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [ROOT / 'index.html', *sorted(ROOT.glob('plan-*.html'))]
OUTPUT = ROOT / '호주여행제안.html'


def build():
    pages = [p.read_text(encoding='utf-8') for p in SOURCES]
    head = re.search(r'<head>(.*?)</head>', pages[0], re.S)[1]
    css = (ROOT / 'assets/site.css').read_text(encoding='utf-8')
    head = re.sub(r'<link\b[^>]*href="assets/site.css"[^>]*>', lambda _: '<style>' + css + '</style>', head)
    head = re.sub(r'<title>.*?</title>', '<title>호주 여행 제안 · 다섯 가지 안 통합본</title>', head)
    head += '<noscript><style>[data-screen][hidden]{display:block!important}</style></noscript>'
    blocks = []
    names = {p.name: ('home' if i == 0 else 'plan-' + str(i)) for i, p in enumerate(SOURCES)}
    nav = '<div class="topbar"><div class="in"><div class="brand">호주 여행 제안 · 통합본</div><nav aria-label="여행안 선택">'
    labels = ['개요', '1 시드니', '2 시드니·해밀턴', '3 해밀턴·골드코스트', '4 골드코스트·해밀턴', '5 멜버른·해밀턴']
    nav += ''.join(f'<a href="#{names[p.name]}">{label}</a>' for p, label in zip(SOURCES, labels)) + '</nav></div></div>'
    for page, source in zip(pages, SOURCES):
        name = names[source.name]
        body = re.search(r'<body\b[^>]*>(.*?)</body>', page, re.S)[1]
        # The canonical layout starts with the global top bar and print controls.
        body = body[body.index('<header'):]
        body = re.sub(r'<script\b[^>]*>.*?</script>', '', body, flags=re.S)
        body = re.sub(r'\bid="([^"]+)"', lambda m: f'id="{name}--{m[1]}"', body)
        body = re.sub(r'href="#([^"]+)"', lambda m: f'href="#{name}--{m[1]}"', body)
        for filename, target in names.items():
            body = body.replace('href="' + filename + '"', 'href="#' + target + '"')
        hidden = '' if name == 'home' else ' hidden'
        blocks.append(f'<div data-screen="{name}" id="{name}"{hidden}>\n{body}\n</div>')
    data = (ROOT / 'assets/places.js').read_text(encoding='utf-8')
    js = (ROOT / 'assets/site.js').read_text(encoding='utf-8')
    return '<!DOCTYPE html>\n<!-- Generated by scripts/build_combined.py; edit individual pages and assets. -->\n<html lang="ko"><head>' + head + '</head><body>' + nav + '<div class="print-controls page"><button type="button" data-print="current">현재 안 인쇄</button><button type="button" data-print="all">전체 안 인쇄</button><span class="small">사진은 인터넷 연결이 필요합니다.</span></div>' + '\n'.join(blocks) + '<script>' + data + '</script><script>' + js + '</script></body></html>\n'


if __name__ == '__main__':
    result = build()
    if '--check' in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != result:
            raise SystemExit('Combined edition is out of date: run python scripts/build_combined.py')
        print('Combined edition matches all canonical pages and shared assets.')
    else:
        OUTPUT.write_text(result, encoding='utf-8')
        print('Built', OUTPUT.name)
